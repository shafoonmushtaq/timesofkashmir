import 'dart:convert';

import '/features/news/domain/entities/Post.dart';

PostModel postModelFromJson(String str) => PostModel.fromJson(json.decode(str));

String postModelToJson(PostModel data) => json.encode(data.toJson());

class PostModel extends Post {
  const PostModel({
    required int? id,
    required DateTime? date,
    required DateTime? dateGmt,
    required Guid? guid,
    required DateTime? modified,
    required DateTime? modifiedGmt,
    required String? slug,
    required String? status,
    required String? type,
    required String? link,
    required Guid? title,
    required Content? content,
    required Content? excerpt,
    required int? author,
    required int? featuredMedia,
    required String? commentStatus,
    required String? pingStatus,
    required bool? sticky,
    required String? template,
    required String? format,
    required String? jetpackFeaturedMediaUrl,
    required Links links,
  }) : super(
            id: id,
            date: date,
            dateGmt: dateGmt,
            guid: guid,
            modified: modified,
            modifiedGmt: modifiedGmt,
            slug: slug,
            status: status,
            type: type,
            link: link,
            title: title,
            content: content,
            excerpt: excerpt,
            author: author,
            featuredMedia: featuredMedia,
            commentStatus: commentStatus,
            pingStatus: pingStatus,
            sticky: sticky,
            template: template,
            format: format,
            jetpackFeaturedMediaUrl: jetpackFeaturedMediaUrl,
            links: links);

  factory PostModel.fromJson(Map<String, dynamic> json) => PostModel(
        id: json["id"],
        date: DateTime.parse(json["date"]),
        dateGmt: DateTime.parse(json["date_gmt"]),
        guid: Guid.fromJson(json["guid"]),
        modified: DateTime.parse(json["modified"]),
        modifiedGmt: DateTime.parse(json["modified_gmt"]),
        slug: json["slug"],
        status: json["status"],
        type: json["type"],
        link: json["link"],
        title: Guid.fromJson(json["title"]),
        content: Content.fromJson(json["content"]),
        excerpt: Content.fromJson(json["excerpt"]),
        author: json["author"],
        featuredMedia: json["featured_media"],
        commentStatus: json["comment_status"],
        pingStatus: json["ping_status"],
        sticky: json["sticky"],
        template: json["template"],
        format: json["format"],
        jetpackFeaturedMediaUrl: json["jetpack_featured_media_url"],
        links: Links.fromJson(json["_links"]),
      );

  Map<String, dynamic> toJson() => {
        "id": id,
        "date": date?.toIso8601String(),
        "date_gmt": dateGmt?.toIso8601String(),
        "guid": guid?.toJson(),
        "modified": modified?.toIso8601String(),
        "modified_gmt": modifiedGmt?.toIso8601String(),
        "slug": slug,
        "status": status,
        "type": type,
        "link": link,
        "title": title?.toJson(),
        "content": content?.toJson(),
        "excerpt": excerpt?.toJson(),
        "author": author,
        "featured_media": featuredMedia,
        "comment_status": commentStatus,
        "ping_status": pingStatus,
        "sticky": sticky,
        "template": template,
        "format": format,
        "jetpack_featured_media_url": jetpackFeaturedMediaUrl,
        "_links": links.toJson(),
      };
}
